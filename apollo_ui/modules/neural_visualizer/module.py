        layout.addWidget(canvas, 1)
        layout.addWidget(details)

        def refresh_status():
            try:
                status = module._status()

                if not status["model_found"]:
                    status_label.setText(
                        "Model: no neural_learning_state.json found"
                    )
                elif not status["trained"]:
                    status_label.setText(
                        "Model: found, but not trained yet"
                    )
                else:
                    status_label.setText(
                        "Model: trained | "
                        f"{status.get('example_count')} examples | "
                        f"{status.get('vocab_size')} features | "
                        f"{status.get('hidden_size')} hidden nodes | "
                        f"Ready for Apollo chat: {status.get('ready_for_use')}"
                    )

            except Exception as exc:
                status_label.setText(
                    f"Model error: {exc}"
                )

        def visualize():
            try:
                result = module._visualize(
                    text_input.text(),
                    max_input_nodes=12,
                    max_hidden_nodes=16,
                )

                canvas.set_data(result)

                outputs = result.get(
                    "outputs",
                    []
                )

                output_lines = [
                    (
                        f"{item['label']}: "
                        f"{item['probability'] * 100:.2f}%"
                    )
                    for item in outputs
                ]

                features = [
                    item["feature"]
                    for item in result.get(
                        "input_nodes",
                        [],
                    )
                ]

                details.setPlainText(
                    f"Input: {result.get('text')}\n"
                    f"Active visible features: {', '.join(features) or 'none'}\n"
                    f"Ready for Apollo chat: {result.get('ready_for_use')}\n\n"
                    + "\n".join(output_lines)
                )

                refresh_status()

            except Exception as exc:
                QMessageBox.warning(
                    page,
                    "Neural Visualizer",
                    str(exc),
                )

