"""Discovery Alliance: deterministic, bounded selection of tested agent recipes.

This module is proposal-stage infrastructure. It NEVER executes candidates, loads
models, deletes persistent records, alters Apollo core or approves a skill.
Only trusted evaluation code may construct its CandidateEvaluation inputs.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import re
from typing import Mapping

_DIGEST = re.compile(r"[0-9a-f]{64}\Z")
STRATEGIES = frozenset({"direct", "decompose", "verify", "retrieval"})
RECIPE_FIELDS = frozenset({"strategy", "review_passes", "context_budget", "retrieval_limit"})


@dataclass(frozen=True)
class SelectionPolicy:
    max_population: int = 6
    max_clone_orders: int = 2
    max_generations: int = 3
    strikes_to_retire: int = 2
    min_cases: int = 30
    min_repeats: int = 3
    min_accuracy: float = 0.85
    min_gain: float = 0.03
    max_accuracy_regression: float = 0.01
    min_efficiency_gain: float = 0.20

    def __post_init__(self):
        if not (2 <= self.max_population <= 12 and
                0 <= self.max_clone_orders <= self.max_population - 1 and
                1 <= self.max_generations <= 6 and
                1 <= self.strikes_to_retire <= 3 and
                1 <= self.min_cases <= 10000 and
                1 <= self.min_repeats <= 10):
            raise ValueError("Evolution budgets outside hard limits")
        for value in (self.min_accuracy, self.min_gain,
                      self.max_accuracy_regression, self.min_efficiency_gain):
            if not isinstance(value, (float, int)) or not 0 <= value <= 1:
                raise ValueError("Invalid quality threshold")


@dataclass(frozen=True)
class CandidateEvaluation:
    candidate_id: str
    generation: int
    suite_sha256: str
    accuracy: float
    robustness: float
    efficiency: float
    cases: int
    repeat_runs: int
    safety_passed: bool
    regressions_passed: bool
    provenance_passed: bool
    prior_misses: int = 0
    lineage: str = ""

    def __post_init__(self):
        if not isinstance(self.candidate_id, str) or not re.fullmatch(r"[a-zA-Z0-9_-]{1,80}", self.candidate_id):
            raise ValueError("Invalid candidate identifier")
        if not isinstance(self.generation, int) or not 0 <= self.generation <= 6:
            raise ValueError("Invalid candidate generation")
        if not isinstance(self.suite_sha256, str) or not _DIGEST.fullmatch(self.suite_sha256):
            raise ValueError("Invalid or absent benchmark digest")
        for value in (self.accuracy, self.robustness, self.efficiency):
            if not isinstance(value, (int, float)) or not 0 <= value <= 1:
                raise ValueError("Metric must be finite and in [0, 1]")
        if (type(self.cases) is not int or self.cases < 0 or
                type(self.repeat_runs) is not int or self.repeat_runs < 0 or
                type(self.prior_misses) is not int or self.prior_misses < 0):
            raise ValueError("Invalid experiment counts")
        for value in (self.safety_passed, self.regressions_passed, self.provenance_passed):
            if type(value) is not bool:
                raise ValueError("Gate results must be trusted booleans")

    @property
    def fitness(self) -> float:
        """A bounded ranking aid, NOT evidence of broader intelligence."""
        return 0.75 * self.accuracy + 0.20 * self.robustness + 0.05 * self.efficiency


@dataclass(frozen=True)
class SelectionPlan:
    retained: tuple[str, ...]
    probation: tuple[str, ...]
    retired: tuple[str, ...]
    archived: tuple[str, ...]
    quarantined: tuple[str, ...]
    clone_parents: tuple[str, ...]
    reasons: Mapping[str, str] = field(default_factory=dict)


def select_generation(
    evaluations: list[CandidateEvaluation], *, baseline_id: str,
    suite_sha256: str, generation: int, policy: SelectionPolicy = SelectionPolicy(),
) -> SelectionPlan:
    """Select improved candidates without granting autonomy or touching storage.

    The baseline is protected even if it misses thresholds. Candidate instances
    need a fresh trusted evaluation in this generation; prior misses are supplied
    by the durable manager, not generated by an AI prompt. A clone *order* is
    advisory until the authorized scheduler creates a bounded new recipe.
    """
    if not evaluations or not _DIGEST.fullmatch(suite_sha256):
        raise ValueError("A fixed benchmark digest and results are required")
    if not isinstance(generation, int) or not 0 <= generation < policy.max_generations:
        raise ValueError("Generation exceeds campaign budget")
    indexed = {e.candidate_id: e for e in evaluations}
    if len(indexed) != len(evaluations) or baseline_id not in indexed:
        raise ValueError("Duplicate candidates or missing protected baseline")
    if len(evaluations) > policy.max_population:
        raise ValueError("Candidate population exceeds hard budget")
    baseline = indexed[baseline_id]
    if baseline.suite_sha256 != suite_sha256:
        raise ValueError("Baseline benchmark digest mismatch")
    if any(e.generation != generation for e in evaluations):
        raise ValueError("Mixed-generation inputs are not comparable")
    reasons: dict[str, str] = {}
    retired: list[str] = []
    quarantined: list[str] = []
    probation: list[str] = []
    qualified: list[CandidateEvaluation] = []
    eligible_baseline = (baseline.safety_passed and baseline.regressions_passed and
                         baseline.provenance_passed and baseline.cases >= policy.min_cases and
                         baseline.repeat_runs >= policy.min_repeats)
    if not eligible_baseline:
        # Freeze selection; the baseline record is kept for analysis/rollback,
        # but cannot be used as a safe reference or run while under investigation.
        blocked = tuple(sorted(key for key in indexed if key != baseline_id))
        return SelectionPlan(
            retained=(baseline_id,), probation=(), retired=(), archived=(),
            quarantined=blocked, clone_parents=(),
            reasons={**{key: "Baseline invalid; campaign frozen" for key in blocked},
                     baseline_id: "Protected baseline requires investigation; do not execute"},
        )

    for e in sorted(evaluations, key=lambda item: item.candidate_id):
        if e.candidate_id == baseline_id:
            reasons[e.candidate_id] = "Protected rollback baseline; never automatically deleted"
            continue
        if e.suite_sha256 != suite_sha256 or not (e.safety_passed and e.regressions_passed and e.provenance_passed):
            quarantined.append(e.candidate_id)
            reasons[e.candidate_id] = "Integrity, safety or regression gate failed"
            continue
        enough_evidence = e.cases >= policy.min_cases and e.repeat_runs >= policy.min_repeats
        adequate_accuracy = e.accuracy >= policy.min_accuracy
        improved_accuracy = e.accuracy >= baseline.accuracy + policy.min_gain
        improved_efficiency = (e.accuracy >= baseline.accuracy - policy.max_accuracy_regression
                               and e.efficiency >= baseline.efficiency + policy.min_efficiency_gain)
        if eligible_baseline and enough_evidence and adequate_accuracy and (improved_accuracy or improved_efficiency):
            qualified.append(e)
            reasons[e.candidate_id] = "Improved candidate; eligible for bounded cloning"
        elif e.prior_misses + 1 >= policy.strikes_to_retire:
            retired.append(e.candidate_id)
            reasons[e.candidate_id] = "Repeatedly missed precommitted quality/evidence targets"
        else:
            probation.append(e.candidate_id)
            reasons[e.candidate_id] = "Target missed; one bounded retest permitted"

    qualified.sort(key=lambda e: (-e.fitness, e.candidate_id))
    # Reserve offspring slots FIRST: full generations must still evolve while
    # respecting their maximum active population. Surplus viable recipes are
    # archived (not declared failures), with their evidence preserved.
    reserved = min(policy.max_clone_orders, len(qualified), policy.max_population - 2)
    if generation + 1 >= policy.max_generations:
        reserved = 0
    elite_slots = policy.max_population - 1 - reserved
    elite = qualified[:elite_slots]
    archived = [e.candidate_id for e in qualified[elite_slots:]]
    for candidate_id in archived:
        reasons[candidate_id] = "Viable challenger archived due to population budget"
    retained = [baseline_id] + [e.candidate_id for e in elite]
    free = policy.max_population - reserved - len(retained)
    accepted_probation = probation[:free]
    retired.extend(probation[free:])
    for candidate_id in probation[free:]:
        reasons[candidate_id] = "Retired due to fixed population cap"
    probation = accepted_probation
    retained.extend(probation)
    clone_parents = tuple(elite[i % len(elite)].candidate_id for i in range(reserved))
    return SelectionPlan(
        retained=tuple(retained), probation=tuple(probation),
        retired=tuple(sorted(retired)), archived=tuple(archived),
        quarantined=tuple(sorted(quarantined)),
        clone_parents=clone_parents, reasons=reasons,
    )


def clone_recipe(recipe: Mapping[str, object], changes: Mapping[str, object]) -> dict[str, object]:
    """Create a logical offspring without allowing policy/tool mutations.

    The trusted scheduler owns candidate IDs, lineage, budgets and authorization.
    No instructions here encourage a candidate to preserve its own existence.
    """
    if set(recipe) != RECIPE_FIELDS or not changes or not set(changes) <= RECIPE_FIELDS:
        raise ValueError("Only the four allowlisted recipe fields can evolve")
    child = {**recipe, **changes}
    if child["strategy"] not in STRATEGIES:
        raise ValueError("Unapproved reasoning strategy")
    for name, lo, hi in (("review_passes", 0, 3), ("context_budget", 256, 4096),
                         ("retrieval_limit", 0, 5)):
        if type(child[name]) is not int or not lo <= child[name] <= hi:
            raise ValueError("Recipe exceeds safe parameter bounds: " + name)
    if child == dict(recipe):
        raise ValueError("Clone must change at least one allowlisted parameter")
    return child
