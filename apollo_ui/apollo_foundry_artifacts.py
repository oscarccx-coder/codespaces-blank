"""Safe Foundry file handoff: bounded project files, no execution, no user-file overwrites."""
from __future__ import annotations
import hashlib
import json
import os
from pathlib import Path, PurePosixPath, PureWindowsPath
import re
import tempfile

MANIFEST = ".foundry-generated.json"
MAX_FILES = 8
MAX_FILE_BYTES = 20000
MAX_TOTAL_BYTES = 65000
EXTENSIONS = {".py", ".json", ".md", ".txt", ".toml", ".qss"}
FORBIDDEN = {"storage", "setup", "models", "config.json", ".git", "__pycache__", "venv", ".venv", "audio"}

def _relative(name):
    if not isinstance(name, str) or not 1 <= len(name) <= 120 or "\\" in name or "\x00" in name:
        raise ValueError("Invalid generated file path")
    pure, win = PurePosixPath(name), PureWindowsPath(name)
    segments = name.split("/")
    if pure.is_absolute() or win.drive or win.root or any(
        not s or s in (".", "..") or s.startswith(".") or s.casefold() in FORBIDDEN
        or not re.fullmatch(r"[A-Za-z0-9_.-]+", s) for s in segments
    ) or len(segments) > 4 or pure.suffix not in EXTENSIONS:
        raise ValueError("Unsafe generated file path: " + name[:120])
    return pure

def _digest(data):
    return hashlib.sha256(data).hexdigest()

def _bundle(value):
    if isinstance(value, str):
        value = json.loads(value)
    if not isinstance(value, dict) or set(value) != {"files", "summary"}:
        raise ValueError("Worker must return JSON with files and summary")
    files = value["files"]
    if not isinstance(value["summary"], str) or len(value["summary"]) > 1500:
        raise ValueError("Invalid worker summary")
    if not isinstance(files, list) or not 1 <= len(files) <= MAX_FILES:
        raise ValueError("Worker must return 1 to 8 files")
    validated, names, size = [], set(), 0
    for item in files:
        if not isinstance(item, dict) or set(item) != {"path", "content"}:
            raise ValueError("Each generated file needs path and content")
        relative = _relative(item["path"])
        name = relative.as_posix()
        if name.casefold() in names:
            raise ValueError("Duplicate generated path")
        names.add(name.casefold())
        if not isinstance(item["content"], str):
            raise ValueError("Generated content must be text")
        data = item["content"].encode("utf-8")
        if not data or len(data) > MAX_FILE_BYTES:
            raise ValueError("Generated file is empty or too large: " + name)
        size += len(data)
        if size > MAX_TOTAL_BYTES:
            raise ValueError("Generated bundle exceeds size limit")
        if relative.suffix == ".json":
            json.loads(item["content"])
        validated.append((name, data))
    return validated, value["summary"]

def save_bundle(project_folder, proposal):
    """Write files only into a private app folder, with edit-detection and no execution."""
    project_folder = Path(project_folder)
    if not project_folder.is_dir() or project_folder.is_symlink():
        raise ValueError("Project workspace unavailable")
    root = project_folder.resolve()
    manifest = root / MANIFEST
    if manifest.is_symlink():
        raise ValueError("Unsafe generated-file manifest")
    try:
        owned = json.loads(manifest.read_text(encoding="utf-8")) if manifest.exists() else {}
    except (OSError, ValueError):
        raise ValueError("Generated-file manifest unreadable; refusing overwrite") from None
    if not isinstance(owned, dict):
        raise ValueError("Invalid generated-file manifest")
    files, summary = _bundle(proposal)
    for name, data in files:
        destination = root.joinpath(*PurePosixPath(name).parts)
        for parent in destination.parents:
            if parent == root:
                break
            if parent.is_symlink():
                raise ValueError("Symlink in generated path: " + name)
        if not destination.resolve().is_relative_to(root) or destination.is_symlink():
            raise ValueError("Generated path escapes workspace: " + name)
        if destination.exists():
            if not destination.is_file() or destination.stat().st_size > MAX_FILE_BYTES:
                raise ValueError("Existing project file not safe to overwrite: " + name)
            if owned.get(name) != _digest(destination.read_bytes()):
                raise ValueError("File was not generated by Foundry or was manually edited: " + name)
    for name, data in files:
        destination = root.joinpath(*PurePosixPath(name).parts)
        destination.parent.mkdir(parents=True, exist_ok=True)
        fd, temp = tempfile.mkstemp(dir=destination.parent, prefix=".foundry-staging-")
        try:
            with os.fdopen(fd, "wb") as output:
                output.write(data)
            os.replace(temp, destination)
        finally:
            if os.path.exists(temp):
                os.unlink(temp)
        owned[name] = _digest(data)
    fd, temp = tempfile.mkstemp(dir=root, prefix=".foundry-manifest-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            json.dump(owned, output, indent=2, sort_keys=True)
        os.replace(temp, manifest)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)
    return {"files": [name for name, _ in files], "summary": summary}
